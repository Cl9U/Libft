#include "libft.h"

char	*ft_strjoin(char const *s1, char const *s2)
{
	size_t	nlen;
	size_t	s1len;
	size_t	s2len;
	char	*str;

	if (!s1 || !s2)
		return (NULL);
	s1len = ft_strlen(s1);
	s2len = ft_strlen(s2);
	nlen = s1len + s2len;
	str = malloc(nlen + 1);
	if (!str)
		return (NULL);
	ft_memcpy(str, s1, s1len);
	ft_memcpy(str + s1len, s2, s2len + 1);
	return (str);
}
